import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;

public class AiPatternDetector {

    private static final int MAX_SCORE = 10;
    private static final int THRESHOLD = 5;

    private static int score = 0;
    private static final List<String> findings = new ArrayList<>();

    public static void main(String[] args) {

        if (args.length != 3) {
            System.err.println(
                    "Usage: AiPatternDetector <source-dir> <report-file> <threshold>"
            );
            System.exit(1);
        }

        Path sourceDir = Path.of(args[0]);
        Path reportFile = Path.of(args[1]);
        int threshold = Integer.parseInt(args[2]);

        if (!Files.isDirectory(sourceDir)) {
            System.err.println("Source directory not found: " + sourceDir);
            System.exit(1);
        }

        try {
            scanDirectory(sourceDir);
            generateReport(reportFile, threshold);

            System.out.println("AI Pattern Score: " + score + "/" + MAX_SCORE);

            if (score >= threshold) {
                System.err.println("AI Detection threshold reached.");
                System.exit(1);
            }

            System.out.println("AI Detection passed.");

        } catch (IOException e) {
            System.err.println("AI Detection error: " + e.getMessage());
            System.exit(1);
        }
    }

    private static void scanDirectory(Path directory) throws IOException {

        try (Stream<Path> files = Files.walk(directory)) {

            files.filter(path -> path.toString().endsWith(".java"))
                    .forEach(AiPatternDetector::analyzeFile);

        }
    }

    private static void analyzeFile(Path file) {

        try {

            String code = Files.readString(file);

            if (code.contains("TODO: implement")
                    || code.contains("Generated by AI")) {
                addFinding(2, file, "AI-generated placeholder or marker");
            }

            if (code.contains("System.out.println")
                    && code.contains("try")
                    && code.contains("catch")) {
                addFinding(1, file, "Repeated generic debugging/error pattern");
            }

            if (code.matches("(?s).*if\\s*\\([^)]*\\)\\s*\\{\\s*\\}.*")) {
                addFinding(1, file, "Empty conditional block");
            }

            if (code.contains("where 1 = 1")) {
                addFinding(2, file, "Generic SQL construction pattern");
            }

            if (code.contains("StringBuilder")
                    && code.contains(".append(")) {
                addFinding(1, file, "String concatenation pattern");
            }

            if (code.contains("UnsupportedOperationException")
                    && code.contains("TODO")) {
                addFinding(2, file, "Unimplemented method pattern");
            }

        } catch (IOException e) {
            System.err.println("Cannot read: " + file);
        }
    }

    private static void addFinding(int points, Path file, String description) {

        if (score >= MAX_SCORE) {
            return;
        }

        int addedPoints = Math.min(points, MAX_SCORE - score);
        score += addedPoints;

        findings.add(
                file + " | +" + addedPoints + " | " + description
        );
    }

    private static void generateReport(Path report, int threshold)
            throws IOException {

        if (report.getParent() != null) {
            Files.createDirectories(report.getParent());
        }

        List<String> output = new ArrayList<>();

        output.add("AI CODE PATTERN DETECTION REPORT");
        output.add("--------------------------------");
        output.add("Maximum Score: " + MAX_SCORE);
        output.add("Threshold: " + threshold);
        output.add("Final Score: " + score + "/" + MAX_SCORE);
        output.add("");

        if (findings.isEmpty()) {
            output.add("No suspicious patterns found.");
        } else {
            output.add("Detected Patterns:");

            for (String finding : findings) {
                output.add("- " + finding);
            }
        }

        output.add("");
        output.add(
                score >= threshold ? "RESULT: FAILED" : "RESULT: PASSED"
        );

        Files.write(report, output);
    }
}
